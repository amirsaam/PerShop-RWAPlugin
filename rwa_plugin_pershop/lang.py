def normalize_lang(raw: object) -> str:
    lang = str(raw or "en").lower()
    return lang if lang in LOCALES else "en"


def shop_lang(shop: dict | None) -> str:
    shop = shop or {}
    return normalize_lang(shop.get("_buyer_lang") or shop.get("lang"))


def L(shop_or_lang: dict | str | None, key: str, **vars: object) -> str:
    """Localized string with English fallback. Never raises on missing keys."""
    lang = shop_or_lang if isinstance(shop_or_lang, str) else shop_lang(shop_or_lang)
    tpl = LOCALES.get(lang, {}).get(key) or LOCALES["en"].get(key) or key
    try:
        return tpl.format(**vars)
    except Exception:
        return tpl


MENU_TEXT_ACTIONS = {
    "buy_subs_btn": "pershop:buy",
    "test_sub_btn": "pershop:test",
    "my_subs_btn": "my_subs",
    "services_btn": "pershop:services",
    "referral_btn": "pershop:ref",
    "tutorial_btn": "pershop:how",
    "support_btn": "pershop:help",
    "account_btn": "account",
}


def menu_action_for_text(text: object) -> str | None:
    """Map a persistent-panel tap (plain-text message) to a menu action.

    Labels are matched in all four locales, so the tap routes correctly
    regardless of the buyer's current language. Never raises.
    """
    try:
        t = (text or "").strip()
        if not t:
            return None
        for loc in LOCALES.values():
            for key, action in MENU_TEXT_ACTIONS.items():
                if loc.get(key) == t:
                    return action
    except Exception:
        pass
    return None
