def menu_action_for_text(text: object) -> str | None:
    """Map a persistent-panel tap (plain-text message) to a menu action.

    Labels are matched in all four locales, so the tap routes correctly
    regardless of the buyer's current language. Never raises.
    """
    try:
        t = (text or "").strip()
        if not t:
            return None
        for loc in LOCALES.values():
            for key, action in MENU_TEXT_ACTIONS.items():
                if loc.get(key) == t:
                    return action
    except Exception:
        pass
    return None
